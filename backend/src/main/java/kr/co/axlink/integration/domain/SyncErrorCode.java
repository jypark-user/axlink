package kr.co.axlink.integration.domain;

import java.util.Set;

public enum SyncErrorCode {
  AI_UNAVAILABLE,
  TOOL_AUTH_FAILED,
  TOOL_RESOURCE_NOT_FOUND,
  TOOL_RATE_LIMITED,
  TOOL_UNAVAILABLE,
  CATALOG_VALIDATION_FAILED,
  PROJECT_ACCESS_DENIED,
  WORK_PRODUCT_TYPE_REJECTED,
  EMBEDDING_DIMENSION_MISMATCH,
  DOCUMENT_PARSE_FAILED,
  INTERNAL_ERROR;

  private static final Set<String> DB_VALUES = Set.of(
      "AI_UNAVAILABLE", "TOOL_AUTH_FAILED", "TOOL_RESOURCE_NOT_FOUND", "TOOL_RATE_LIMITED",
      "TOOL_UNAVAILABLE", "CATALOG_VALIDATION_FAILED", "PROJECT_ACCESS_DENIED",
      "WORK_PRODUCT_TYPE_REJECTED", "EMBEDDING_DIMENSION_MISMATCH", "DOCUMENT_PARSE_FAILED",
      "INTERNAL_ERROR");

  public static boolean isAllowed(String code) {
    return code != null && DB_VALUES.contains(code);
  }
}
